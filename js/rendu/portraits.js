export const aPortrait = (type) => Object.prototype.hasOwnProperty.call(PORTRAITS, type);

/** Dessine le portrait du type dans le cercle (cx, cy, r), sur un fond uni (sombre par défaut). @returns {boolean} faux si ce type n'a pas de portrait */
export function dessinerPortrait(ctx, type, cx, cy, r, fond = '#2b2622') {
  if (!aPortrait(type)) return false;
  ctx.save();
  ctx.beginPath();
  ctx.arc(cx, cy, r, 0, Math.PI * 2);
  ctx.clip();
  ctx.fillStyle = fond;
  ctx.fill();
  ctx.translate(cx, cy);
  ctx.scale(r * 0.92, r * 0.92);
  PORTRAITS[type](ctx);
  ctx.restore();
  return true;
}
